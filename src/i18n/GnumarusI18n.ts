const CATALOG: Record<GnumarusLocale, Record<GnumarusMessageKey, string>> = {
  en: EN_STRINGS as unknown as Record<GnumarusMessageKey, string>,
  "pt-BR": PT_BR_STRINGS,
};

let activeLocale: GnumarusLocale = "en";

/** Active locale used by `tr()`; updated when the language setting changes. */
export function getActiveLocale(): GnumarusLocale {
  return activeLocale;
}

export function setActiveLocale(locale: GnumarusLocale): void {
  activeLocale = locale;
}

/**
 * Translate a catalog key with optional `{name}` interpolation. Unknown
 * keys fall back to the English text (or the key itself when absent there).
 */
export function tr(key: GnumarusMessageKey, params?: Record<string, string | number>): string {
  const table = CATALOG[activeLocale] ?? CATALOG.en;
  let text: string = table[key] ?? CATALOG.en[key] ?? key;
  if (params !== undefined) {
    for (const [name, value] of Object.entries(params)) {
      text = text.split(`{${name}}`).join(String(value));
    }
  }
  return text;
}

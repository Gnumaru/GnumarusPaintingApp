/**
 * UI localization: typed message catalog with English (default) and
 * Brazilian Portuguese translations, `{name}` interpolation, and locale
 * resolution (`system` follows the browser language with English fallback).
 * Keyboard shortcuts never change; only visible UI texts and console
 * messages go through this catalog.
 */

export type GnumarusLocale = "en" | "pt-BR";

/** Language setting: a concrete locale or `system` (browser language). */
export type GnumarusLocaleSetting = "system" | GnumarusLocale;

export const DEFAULT_LOCALE_SETTING: GnumarusLocaleSetting = "system";

/**
 * Resolve a language setting to a concrete locale. `browserLanguage` is a
 * BCP 47 tag such as `navigator.language`; base-language matches count as
 * similar (e.g. `pt-PT` resolves to `pt-BR`), anything else falls back to
 * English.
 */
export function resolveLocale(setting: GnumarusLocaleSetting, browserLanguage?: string): GnumarusLocale {
  if (setting === "en" || setting === "pt-BR") {
    return setting;
  }
  const tag =
    browserLanguage ?? (typeof navigator !== "undefined" ? navigator.language : "") ?? "";
  const base = tag.toLowerCase().split("-")[0];
  if (base === "pt") {
    return "pt-BR";
  }
  return "en";
}

